"""Generate the pre-1962 Earth orientation files historicalDeltaT.txt and eopc01_polar_motion_1846-1961.txt.

Usage (requires numpy), from any directory:

    python make_pre1962_eop_files.py [output directory, default: the parent directory of this script]

Source data (in the same directory as this script, downloaded on 2026-10-29):

- eopc01.iau2000.1846-now: IERS EOP C01 series (IAU 2000), https://hpiers.obspm.fr/iers/eop/eopc01/eopc01.iau2000.1846-now
  Columns used: MJD, x, y [arcsec], UT1 - TAI [s] (fill value 99.99 before 1956).
- delta_t.npz: copy of Table S15.2020 of Morrison, Stephenson, Hohenkerk & Zawilski (2021), Proc. R. Soc. A 477: 20200776
  (addendum to Stephenson, Morrison & Hohenkerk (2016), Proc. R. Soc. A 472: 20160404), as bundled with Skyfield (MIT license):
  https://github.com/skyfielders/python-skyfield/blob/master/skyfield/data/delta_t.npz
  (sha256 2d12bd3e789543b78a1f53c8b76ed7fecffdf7e5149cfb6a0aed21a8b3db5ff6). The original table,
  http://astro.ukho.gov.uk/nao/lvm/Table-S15.2020.txt, was not reachable on 2026-10-29. The values agree with the tabulated
  spline at https://hpiers.obspm.fr/eop-pc/earthor/ut1lod/lod-eclipses.html (e.g. 33.62 s at 1962.0).
- historicalDeltaT_usno_1620-2009.txt: previous historicalDeltaT.txt of tudat-resources, yearly Delta T values of the
  Astronomical Almanac / USNO, https://webspace.science.uu.nl/~gent0113/deltat/deltat.htm

historicalDeltaT.txt contains Delta T = TT - UT1 [s] against year = 2000 + (TT - J2000) / Julian year, from:

- -13200 to -800, every 100 years: long-term parabola -320 + 32.5 ((year - 1825) / 100)^2 s of Stephenson et al. (2016),
  offset to be continuous with the spline at -720
- -720 to 1947, yearly: spline of Table S15.2020
- 1948 to 1955, yearly: Astronomical Almanac / USNO. The spline differs from atomic time by 0.2 to 0.6 s after 1955, and from
  the Astronomical Almanac values (which join atomic time in 1956) by 0.01 s at 1948, increasing to 0.66 s at 1955
- 1956.0 to 1962.0, every 0.05 years: IERS EOP C01, 32.184 s - (UT1 - TAI). The last C01 epoch before 1962
  (MJD 37664.804) is replaced by the next value, with which it agrees to 0.2 ms
- 1962.0: IERS EOP C04 at 1962-01-01, 32.184 + (TAI - UTC) - (UT1 - UTC) = 32.184 + 1.845858 - 0.0326338 s, so that UT1 is
  continuous where tudat switches from this table to the EOP file
- 1963 to 2009, yearly: Astronomical Almanac / USNO, only used to shape the interpolation up to 1962

eopc01_polar_motion_1846-1961.txt contains the C01 polar motion (MJD, x, y [arcsec]) before the start of the C04 data
(MJD 37665, 1962-01-01).
"""

import os
import sys

import numpy as np

source_dir = os.path.dirname(os.path.abspath(__file__))
output_dir = sys.argv[1] if len(sys.argv) > 1 else os.path.dirname(source_dir)

# Table S15.2020: rows are K_i, K_i+1, a3, a2, a1, a0, with Delta T = a0 + a1 t + a2 t^2 + a3 t^3, t = (year - K_i) / (K_i+1 - K_i)
table = np.load(os.path.join(source_dir, "delta_t.npz"), allow_pickle=False)["Table-S15.2020.txt"]
start, end, a3, a2, a1, a0 = table
assert np.allclose(a0[1:], (a0 + a1 + a2 + a3)[:-1], atol=2e-3), "spline segments not continuous"


def smh_delta_t(year):
    i = np.searchsorted(end, year, side="left")
    t = (year - start[i]) / (end[i] - start[i])
    return a0[i] + t * (a1[i] + t * (a2[i] + t * a3[i]))


def parabola_delta_t(year):
    return -320.0 + 32.5 * ((year - 1825.0) / 100.0) ** 2


usno = dict(
    np.loadtxt(
        os.path.join(source_dir, "historicalDeltaT_usno_1620-2009.txt"), delimiter=",", comments="#"
    )
)

c01 = np.loadtxt(
    os.path.join(source_dir, "eopc01.iau2000.1846-now"), comments="#", usecols=(0, 1, 2, 3)
)
assert np.all(np.diff(c01[:, 0]) > 0.0)
c01_year = 2000.0 + (c01[:, 0] - 51544.5) / 365.25

c04_delta_t_1962 = 32.184 + 1.845858 - 0.0326338

rows = []
parabola_offset = smh_delta_t(-720.0) - parabola_delta_t(-720.0)
rows += [(year, parabola_delta_t(year) + parabola_offset) for year in range(-13200, -799, 100)]
rows += [(year, smh_delta_t(year)) for year in range(-720, 1948)]
rows += [(year, usno[year]) for year in range(1948, 1956)]
c01_ut1 = (c01_year >= 1955.99) & (c01[:, 0] < 37664.0) & (c01[:, 3] < 99.0)
rows += [
    (year, 32.184 - ut1_minus_tai)
    for year, ut1_minus_tai in zip(c01_year[c01_ut1], c01[c01_ut1, 3])
]
rows += [(1962.0, c04_delta_t_1962)]
rows += [(year, usno[year]) for year in range(1963, 2010)]
years, delta_t = np.array(rows).T
assert np.all(np.diff(years) > 0.0)

with open(os.path.join(output_dir, "historicalDeltaT.txt"), "w") as file:
    file.write("# Delta T = TT - UT1 [s], against year = 2000 + (TT - J2000) / Julian year\n")
    file.write(
        "# Generated by generation/make_pre1962_eop_files.py, which documents the sources and choices in detail\n"
    )
    file.write(
        "# -13200 to -800: long-term parabola -320 + 32.5 ((year - 1825) / 100)^2 of Stephenson, Morrison & Hohenkerk (2016),\n"
    )
    file.write(f"#   offset by {parabola_offset:.1f} s to be continuous with the spline at -720\n")
    file.write(
        "# -720 to 1947: spline of Stephenson, Morrison & Hohenkerk (2016), Proc. R. Soc. A 472: 20160404, updated by Morrison,\n"
    )
    file.write(
        "#   Stephenson, Hohenkerk & Zawilski (2021), Proc. R. Soc. A 477: 20200776 (Table S15.2020, copy bundled with Skyfield)\n"
    )
    file.write(
        "# 1948 to 1955: Astronomical Almanac / USNO values (https://webspace.science.uu.nl/~gent0113/deltat/deltat.htm)\n"
    )
    file.write(
        "# 1956 to 1962: IERS EOP C01, 32.184 s - (UT1 - TAI) (https://hpiers.obspm.fr/iers/eop/eopc01/eopc01.iau2000.1846-now)\n"
    )
    file.write(
        "# 1962.0: IERS EOP C04 at 1962-01-01 (32.184 + 1.845858 - 0.0326338 s), for continuity with the EOP data\n"
    )
    file.write(
        "# 1963 to 2009: Astronomical Almanac / USNO values (only used to shape the interpolation up to 1962)\n"
    )
    for year, value in zip(years, delta_t):
        file.write(f"{year:.4f},{value:.4f}\n" if year % 1.0 else f"{int(year)},{value:.4f}\n")

pole = c01[c01[:, 0] < 37665.0, :3]
assert np.all(np.abs(pole[:, 1:]) < 1.0), "fill values in C01 polar motion"

with open(os.path.join(output_dir, "eopc01_polar_motion_1846-1961.txt"), "w") as file:
    file.write("# IERS EOP C01 (IAU 2000) polar motion before the start of EOP C04 (1962-01-01)\n")
    file.write("# Source: https://hpiers.obspm.fr/iers/eop/eopc01/eopc01.iau2000.1846-now\n")
    file.write("# Generated by generation/make_pre1962_eop_files.py\n")
    file.write("# MJD x [arcsec] y [arcsec]\n")
    for mjd, x, y in pole:
        file.write(f"{mjd:.3f} {x:.6f} {y:.6f}\n")
