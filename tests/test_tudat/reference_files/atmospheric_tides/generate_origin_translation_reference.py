#!/usr/bin/env python3
"""Run independent optional Fortran complex-Fourier/cross-product reference; production is C++."""

import argparse
import hashlib
import json
import os
from pathlib import Path
import subprocess
import tempfile


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--compiler", default=os.environ.get("FC", "gfortran"))
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    root = Path(__file__).resolve().parent
    provenance = json.loads((root / "origin_translation_provenance.json").read_text())
    if (
        hashlib.sha256((root / "origin_translation_reference.f90").read_bytes()).hexdigest()
        != provenance["reference_source_sha256"]
    ):
        raise RuntimeError("Independent reference source checksum mismatch")
    with tempfile.TemporaryDirectory(prefix="tudat-atmospheric-origin-") as temp:
        executable = Path(temp) / "reference"
        subprocess.run(
            [
                args.compiler,
                "-std=f2008",
                "-O0",
                str(root / "origin_translation_reference.f90"),
                "-o",
                str(executable),
            ],
            check=True,
        )
        output = subprocess.run(
            [str(executable)], text=True, capture_output=True, check=True
        ).stdout
    lines = [
        "// Generated by independent complex-Fourier Fortran and Cartesian cross products.",
        "// See origin_translation_reference.f90 and generate_origin_translation_reference.py.",
        "// clang-format off",
        "struct AtmosphericOriginReference { double ut1; double cartesian[3]; double radialNorthEast[3]; };",
        "static const AtmosphericOriginReference atmosphericOriginReferences[] = {",
    ]
    for line in output.splitlines():
        values = [float(value) for value in line.split()]
        if len(values) != 7:
            raise RuntimeError("Unexpected independent reference output")
        lines.append(
            "    { "
            + repr(values[0])
            + ", { "
            + ", ".join(repr(v) for v in values[1:4])
            + " }, { "
            + ", ".join(repr(v) for v in values[4:])
            + " } },"
        )
    lines += ["};", "// clang-format on", ""]
    generated = "\n".join(lines)
    target = root / "origin_translation_reference.h"
    if args.check:
        if target.read_text() != generated:
            raise RuntimeError("Frozen independent origin references differ")
    else:
        target.write_text(generated)
    print(
        "Verified independent atmospheric origin references"
        if args.check
        else "Generated independent atmospheric origin references"
    )


if __name__ == "__main__":
    main()
