#!/usr/bin/env python3
"""Execute checksum-pinned original LAGINT and DAT; never call Tudat."""

import argparse
import datetime
import hashlib
import json
import pathlib
import subprocess
import urllib.request

HERE = pathlib.Path(__file__).resolve().parent
INPUTS = [
    ("daily", 59000, [-0.2541, -0.2546, -0.2554, -0.2559, -0.2562, -0.2565, -0.2567, -0.2569]),
    ("leap", 57751, [-0.3981, -0.3992, -0.4000, 0.5991, 0.5985, 0.5978, 0.5971, 0.5965]),
    (
        "drift",
        37665,
        [0.0326338, 0.0320547, 0.0315526, 0.0311116, 0.0307005, 0.0302784, 0.0298064, 0.0292343],
    ),
]
X = [-0.100, -0.080, 0.010, 0.060, 0.020, 0.140, 0.100, 0.120]
Y = [0.210, 0.208, 0.209, 0.213, 0.219, 0.218, 0.222, 0.225]
DX = [0.00010, 0.00011, 0.00009, 0.00014, 0.00012, 0.00013, 0.00008, 0.00010]
DY = [-0.00020, -0.00019, -0.00017, -0.00018, -0.00021, -0.00020, -0.00018, -0.00016]
LOD = [0.00110, 0.00115, 0.00121, 0.00118, 0.00103, 0.00095, 0.00088, 0.00081]
QUERIES = [0.0, 0.125, 0.75, 1.25, 2.5, 3.0, 3.999, 5.5, 6.875]


def civil(mjd):
    instant = datetime.datetime(1858, 11, 17) + datetime.timedelta(days=mjd)
    return f"{instant.year} {instant.month} {instant.day} {mjd % 1:.17g}"


def main():
    parser = argparse.ArgumentParser(__doc__)
    parser.add_argument("--reference-dir", type=pathlib.Path, required=True)
    parser.add_argument("--compiler", default="gfortran")
    parser.add_argument("--download", action="store_true")
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    cache = args.reference_dir.resolve()
    cache.mkdir(parents=True, exist_ok=True)
    sources = json.loads((HERE / "sources.json").read_text())["files"]
    for name, provenance in sources.items():
        target = cache / name
        if args.download and not target.exists():
            target.write_bytes(urllib.request.urlopen(provenance["url"]).read())
        if hashlib.sha256(target.read_bytes()).hexdigest() != provenance["sha256"]:
            raise RuntimeError(f"Reference checksum mismatch: {target}")
    executable = cache / "lagrange_reference_driver"
    subprocess.run(
        [
            args.compiler,
            "-O0",
            "-ffixed-line-length-none",
            str(HERE / "reference_driver.f90"),
            str(cache / "interp.f"),
            str(cache / "DAT.F"),
            str(cache / "CAL2JD.F"),
            "-o",
            str(executable),
        ],
        check=True,
    )
    header = [
        "// Generated by executing original Paris Observatory LAGINT and SOFA DAT.",
        "// clang-format off",
        "#pragma once",
        "#include <array>",
        "namespace interpolation_reference {",
        "struct Sample { double utcMjd; std::array<double, 6> fields; };",
        "struct Query { double utcMjd; double taiSecondsSinceFirst; std::array<double, 6> fields; };",
        "struct Dataset { double firstDat; std::array<Sample, 8> samples; std::array<Query, 9> queries; };",
        "inline const std::array<Dataset, 3> datasets = {{",
    ]
    csv = [
        "dataset,utc_mjd,tai_seconds_since_first,pm_x_arcsec,pm_y_arcsec,ut1_minus_tai_s,dx_arcsec,dy_arcsec,lod_s"
    ]
    for label, start, dut1 in INPUTS:
        samples = [(start + i, [X[i], Y[i], dut1[i], DX[i], DY[i], LOD[i]]) for i in range(8)]
        text = [
            civil(mjd) + f" {mjd} " + " ".join(f"{v:.17g}" for v in fields)
            for mjd, fields in samples
        ]
        text += [str(len(QUERIES))]
        text += [civil(start + q) + f" {start + q:.17g}" for q in QUERIES]
        lines = (
            subprocess.check_output([str(executable)], input=("\n".join(text) + "\n").encode())
            .decode()
            .splitlines()
        )
        first_dat = float(lines[0])
        outputs = [list(map(float, line.split())) for line in lines[1:]]
        header += [f"  Dataset{{{first_dat:.17g}, {{{{"]
        header += [
            f"    Sample{{{mjd:.17g}, {{{{" + ", ".join(f"{v:.17g}" for v in fields) + "}}},"
            for mjd, fields in samples
        ]
        header += ["  }}, {{"]
        header += [
            f"    Query{{{values[0]:.17g}, {values[1]:.17g}, {{{{"
            + ", ".join(f"{v:.17g}" for v in values[2:])
            + "}}},"
            for values in outputs
        ]
        header += ["  }}},"]
        csv += [label + "," + ",".join(f"{v:.17g}" for v in values) for values in outputs]
    header += ["}};", "} // namespace interpolation_reference", "// clang-format on", ""]
    for name, contents in [
        ("expected.h", "\n".join(header)),
        ("expected.csv", "\n".join(csv) + "\n"),
    ]:
        target = HERE / name
        if args.check:
            if target.read_text() != contents:
                raise RuntimeError(f"Generated output differs: {target}")
        else:
            target.write_text(contents)


if __name__ == "__main__":
    main()
